"""Migraciones contra un PostgreSQL 17 real (testcontainers): `upgrade head` y `alembic check`.

Marcado `db`: queda fuera de `uv run pytest` (`-m 'not db'` en `addopts`) y corre con
`uv run pytest -m db --no-cov` (gate `migrations`). Requiere Docker: si no está, el test falla.
"""

import os
from collections.abc import Iterator
from pathlib import Path
from typing import Final

import pytest
from alembic import command
from alembic.config import Config
from testcontainers.community.postgres import PostgresContainer

pytestmark = pytest.mark.db

BACKEND_DIR: Final = Path(__file__).resolve().parents[1]
POSTGRES_IMAGE: Final = "postgres:17"
# Socket que se monta en el contenedor Ryuk (limpieza de contenedores). Docker Desktop en macOS
# expone ~/.docker/run/docker.sock, que no se puede montar; /var/run/docker.sock sí, y es el
# socket estándar en Linux (CI). Se respeta un override ya definido en el entorno.
DOCKER_SOCKET_ENV: Final = "TESTCONTAINERS_DOCKER_SOCKET_OVERRIDE"
DEFAULT_DOCKER_SOCKET: Final = "/var/run/docker.sock"


@pytest.fixture(scope="module")
def postgres_url() -> Iterator[str]:
    """Levanta un PostgreSQL 17 vacío y devuelve su URL con el driver psycopg 3."""
    with pytest.MonkeyPatch.context() as mp:
        if not os.environ.get(DOCKER_SOCKET_ENV):
            mp.setenv(DOCKER_SOCKET_ENV, DEFAULT_DOCKER_SOCKET)
        with PostgresContainer(POSTGRES_IMAGE, driver="psycopg") as container:
            yield container.get_connection_url()


@pytest.fixture
def alembic_config(postgres_url: str) -> Config:
    """Config de `backend/alembic.ini` apuntando al contenedor (la opción gana sobre `Settings`)."""
    config = Config(BACKEND_DIR / "alembic.ini")
    # configparser interpola `%`: se escapa por si la URL lo contiene.
    config.set_main_option("sqlalchemy.url", postgres_url.replace("%", "%%"))
    return config


def test_upgrade_head_y_sin_drift(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    # Falla con `AutogenerateDiffsDetected` si los modelos ORM tienen cambios sin migración.
    command.check(alembic_config)
